"""One visitor catalogue for asset preparation and the native renderer."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def people(root=ROOT):
    return json.loads((root / 'gallery_people.json').read_text(encoding='utf-8'))['people']

def animals(root=ROOT):
    return json.loads((root/"gallery_people.json").read_text(encoding="utf-8")).get("animals",[])

def actors(root=ROOT):
    return people(root)+animals(root)

def header():
    visitors = people()
    names = ['horse_statue_01', 'antique_ceramic_vase_01', 'chinese_armchair', 'vintage_video_camera']
    names += [p['name'] for p in actors()]
    return ('// Generated by gallery_catalog.py from gallery_people.json.\n'
            f'constexpr unsigned VisitorCount={len(visitors)},AnimalCount={len(animals())},ActorCount=VisitorCount+AnimalCount,VarietyCount=4+ActorCount,MeshCount=14+ActorCount*4,RaySRVCount=7+VarietyCount;\n'
            'constexpr const char* AssetNames[VarietyCount]={' + ','.join(json.dumps(n) for n in names) + '};\n'
            'constexpr const wchar_t* VisitorLabels[VisitorCount]={' + ','.join('L'+json.dumps(p['label']) for p in visitors) + '};\n')

def generate():
    (ROOT/'gallery_people.inc').write_text(header(), encoding='utf-8')
    (ROOT/'gallery_assets.hlsli').write_text(f'// Generated by gallery_catalog.py.\n#define GALLERY_ASSET_COUNT {4+len(actors())}\n',encoding='utf-8')

if __name__ == '__main__':
    generate()
